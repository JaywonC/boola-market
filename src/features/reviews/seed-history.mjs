export function reviewHistorySeed() {
  const listings = [];
  const orders = [];
  const reviews = [];
  for (const sale of PAST_SALES) {
    if (sale.sellerId === sale.buyerId) {
      throw new Error(`Seed sale ${sale.id} has the same buyer and seller.`);
    }
    const listingId = `lst_hist_${sale.id}`;
    const orderId = `ord_hist_${sale.id}`;
    listings.push({
      id: listingId,
      sellerId: sale.sellerId,
      title: sale.title,
      description: sale.description,
      priceCents: sale.priceCents,
      category: sale.category,
      ticketType: sale.category === "tickets" ? (sale.ticketType ?? "other") : null,
      photos: [],
      condition: sale.condition,
      listingType: "fixed",
      status: "sold",
      seniorMoveOut: Boolean(sale.seniorMoveOut),
      auctionEndsAt: null,
      createdAt: sale.createdAt,
    });
    orders.push({
      id: orderId,
      listingId,
      buyerId: sale.buyerId,
      sellerId: sale.sellerId,
      priceCents: sale.priceCents,
      status: "completed",
      createdAt: sale.soldAt,
    });
    if (sale.review) {
      reviews.push({
        id: `rev_hist_${sale.id}`,
        orderId,
        reviewerId: sale.buyerId,
        sellerId: sale.sellerId,
        rating: sale.review.rating,
        body: sale.review.body,
        createdAt: sale.review.createdAt,
      });
    }
  }
  return { listings, orders, reviews };
}
